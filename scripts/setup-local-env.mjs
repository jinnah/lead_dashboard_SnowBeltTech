#!/usr/bin/env node
// Generates .env.local for LOCAL development from the running local Supabase
// stack. Never prints secret values, refuses non-local Supabase URLs, refuses
// to overwrite an existing .env.local unless --force is given, and verifies the
// file is git-ignored (deleting it if not).
//
//   pnpm run env:local            (requires `pnpm run db:start` first)
//   pnpm run env:local -- --force (replace an existing .env.local)

import { randomBytes } from "node:crypto";
import { existsSync, unlinkSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, ".env.local");
const force = process.argv.includes("--force");

function fail(msg) {
  console.error(`[env:local] ERROR: ${msg}`);
  process.exit(1);
}

if (existsSync(target) && !force) fail(".env.local already exists; re-run with `-- --force` to replace it");

// Read local stack status (captured, never echoed).
const status = spawnSync(process.platform === "win32" ? "pnpm.cmd" : "pnpm", ["exec", "supabase", "status", "-o", "env"], {
  cwd: root, encoding: "utf8", shell: process.platform === "win32",
});
if (status.status !== 0) fail("local Supabase is not running (pnpm run db:start)");
const vars = {};
for (const line of status.stdout.split(/\r?\n/)) {
  const m = /^([A-Z_]+)="?([^"]*)"?$/.exec(line.trim());
  if (m) vars[m[1]] = m[2];
}
const apiUrl = vars.API_URL;
const serviceRole = vars.SERVICE_ROLE_KEY || vars.SECRET_KEY;
const anon = vars.ANON_KEY || vars.PUBLISHABLE_KEY;
if (!apiUrl || !serviceRole || !anon) fail("could not read API_URL / service-role / anon values from supabase status");

let host;
try { host = new URL(apiUrl).hostname; } catch { fail("API_URL is not a valid URL"); }
if (!["127.0.0.1", "localhost", "::1"].includes(host)) fail(`refusing non-local Supabase URL host "${host}"`);

const token = randomBytes(32).toString("hex"); // 64 hex chars
const content = [
  "# Generated by scripts/setup-local-env.mjs for LOCAL development only. Ignored by git. Do not share.",
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}`,
  `SUPABASE_URL=${apiUrl}`,
  `SUPABASE_SERVICE_ROLE_KEY=${serviceRole}`,
  `N8N_INGEST_TOKEN=${token}`,
  "",
].join("\n");
writeFileSync(target, content, { encoding: "utf8", mode: 0o600 });

const ignored = spawnSync("git", ["check-ignore", "-q", ".env.local"], { cwd: root });
if (ignored.status !== 0) {
  unlinkSync(target);
  fail(".env.local is NOT git-ignored; file removed. Fix .gitignore before generating secrets.");
}
console.log(`[env:local] wrote .env.local (git-ignored) with: NEXT_PUBLIC_SUPABASE_URL, NEXT_PUBLIC_SUPABASE_ANON_KEY, SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, N8N_INGEST_TOKEN`);
console.log(`[env:local] Supabase URL ${apiUrl}; ingestion token: 64 hex characters (not shown)`);
